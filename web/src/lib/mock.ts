// SIMULATED fixtures for the UI-002 prototype. These responses do NOT come from
// the Rust pipeline; real wiring is UI-003 (Axum API) and UI-004 (connect).
export type Source = { source: string; section: string; page: number | null; text: string };
export type IngestResult = {
  ok: boolean;
  source?: string;
  chunks?: number;
  message: string;
  incompletePages?: number[];
};
export type QueryResult = {
  ok: boolean;
  answer?: string;
  sources?: Source[];
  message: string;
  insufficient?: boolean;
};

export const SCENARIOS = [
  "success",
  "empty",
  "insufficient-evidence",
  "connection-failure",
  "invalid-file",
  "incomplete-pdf",
  "loading",
] as const;
export type Scenario = (typeof SCENARIOS)[number];

export function mockIngest(scenario: Scenario, filename: string): IngestResult {
  switch (scenario) {
    case "invalid-file":
      return {
        ok: false,
        message: `Unsupported file type: ${filename}. Supported: .md, .markdown, .txt, .pdf (OCR is not offered).`,
      };
    case "incomplete-pdf":
      return {
        ok: true,
        source: filename,
        chunks: 1,
        message: "Ingested the readable page(s); OCR is required for the rest.",
        incompletePages: [2],
      };
    case "connection-failure":
      return { ok: false, message: "Could not reach the ingestion API (connection refused)." };
    default:
      return { ok: true, source: filename, chunks: 3, message: "Ingested 3 chunks." };
  }
}

export function mockQuery(scenario: Scenario, question: string): QueryResult {
  switch (scenario) {
    case "empty":
      return { ok: true, message: "No chunks stored yet — ingest a document first.", insufficient: true };
    case "insufficient-evidence":
      return {
        ok: true,
        message: "The retrieved evidence does not answer the question.",
        insufficient: true,
      };
    case "connection-failure":
      return { ok: false, message: "Could not reach the query API (connection refused)." };
    default:
      return {
        ok: true,
        answer: `(mock) Grounded answer for: “${question}”. This text is simulated, not generated by the Rust pipeline.`,
        sources: [
          {
            source: "loan-policy.md",
            section: "Late payments",
            page: 1,
            text: "A late fee is assessed on the first day after the due date.",
          },
          {
            source: "loan-policy.md",
            section: "Fees",
            page: null,
            text: "Page metadata is unavailable for this section.",
          },
        ],
        message: "Answered from 2 retrieved chunks.",
      };
  }
}
